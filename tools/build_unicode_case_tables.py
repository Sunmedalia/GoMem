#!/usr/bin/env python3
"""Generate bounded native casing tables from checksum-pinned Unicode 16 data."""
import argparse
import hashlib
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
VERSION = '16.0.0'
FILES = {
    'UnicodeData.txt': 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f',
    'SpecialCasing.txt': '8d5de354eef79f2395a54c9c7dcebbaf3d30fc962d0f85611ea97aa973a0c451',
    'DerivedCoreProperties.txt': '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd',
}
OUTPUT = ROOT/'pkg/winpath/case_tables.go'


def load(directory, name):
    path = directory/name
    if not path.exists():
        directory.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(f'https://www.unicode.org/Public/{VERSION}/ucd/{name}', timeout=30) as response:
            raw = response.read((4 << 20) + 1)
        if len(raw) > 4 << 20:
            raise ValueError('Unicode source exceeds size bound')
        if hashlib.sha256(raw).hexdigest() != FILES[name]:
            raise ValueError('Unicode download digest mismatch')
        path.write_bytes(raw)
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != FILES[name]:
        raise ValueError(f'Unicode source digest mismatch: {name}')
    return raw.decode('utf-8')


def generate(directory):
    lower, upper = {}, {}
    for line in load(directory, 'UnicodeData.txt').splitlines():
        fields = line.split(';')
        code = int(fields[0], 16)
        for table, index in ((lower, 13), (upper, 12)):
            if fields[index]:
                table[code] = [int(fields[index], 16)]
    for line in load(directory, 'SpecialCasing.txt').splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(';')]
        if fields[4]:
            # Only Final_Sigma is locale-independent; native code handles it
            # using original-string Cased and Case_Ignorable contexts.
            if fields[4] != 'Final_Sigma' and not any(tag in fields[4].split() for tag in ('tr', 'az', 'lt')):
                raise ValueError('unknown conditional casing rule')
            continue
        code = int(fields[0], 16)
        lower[code] = [int(value, 16) for value in fields[1].split()]
        upper[code] = [int(value, 16) for value in fields[3].split()]
    properties = {'Cased': [], 'Case_Ignorable': []}
    for line in load(directory, 'DerivedCoreProperties.txt').splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(';')]
        if fields[1] not in properties:
            continue
        bounds = fields[0].split('..')
        properties[fields[1]].append((int(bounds[0], 16), int(bounds[-1], 16)))
    out = ['// Code generated by tools/build_unicode_case_tables.py; DO NOT EDIT.',
           '// Unicode 16.0.0 data: see LICENSES/Unicode-3.0.txt and generator SHA256 pins.',
           'package winpath', '', 'const UnicodeVersion = "16.0.0"', '']
    for name, table in (('lowerMappings', lower), ('upperMappings', upper)):
        out.append(f'var {name} = [...]caseMapping'+'{')
        for code, mapping in sorted(table.items()):
            if mapping == [code]:
                continue
            literal = ''.join('\\U%08x' % value for value in mapping)
            out.append(f'\t{{0x{code:x}, "{literal}"}},')
        out += ['}', '']
    for prop, name in (('Cased', 'casedRanges'), ('Case_Ignorable', 'ignorableRanges')):
        merged = []
        for start, end in sorted(properties[prop]):
            if merged and start <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
            else:
                merged.append((start, end))
        out.append(f'var {name} = [...]runeRange'+'{')
        out.extend(f'\t{{0x{start:x}, 0x{end:x}}},' for start, end in merged)
        out += ['}', '']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', type=Path, default=ROOT/'.cache/unicode-16.0.0')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(args.data_dir)
    if args.check:
        if OUTPUT.read_text() != output:
            raise ValueError('Unicode case tables differ')
    else:
        OUTPUT.write_text(output)
    print('checksum-pinned Unicode 16 casing and context tables verified')


if __name__ == '__main__':
    main()
