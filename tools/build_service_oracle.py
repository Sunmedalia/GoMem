#!/usr/bin/env python3
"""Generate service layout facts and independent object-decoder fixtures using the pinned Volatility source."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import tarfile
from types import SimpleNamespace
from baseline_matrix import tree_digest

ROOT = Path(__file__).resolve().parents[1]
COMMIT = '881e970121c16f0932fb9d16fbd5fb258cbcbf75'
FACTS = ROOT / 'internal/plugins/windows_service_layout_data.go'
OUTPUT = ROOT / 'internal/plugins/testdata/windows-service-oracle.json'
VERSIONS = ROOT / 'internal/plugins/testdata/windows-service-versions.json'


def generate(source):
    lock = json.loads((ROOT / 'baseline.lock.json').read_text())
    if tree_digest(source) != lock['python_tree_sha256']:
        raise ValueError('service oracle requires the pinned Python tree')
    archive = ROOT / '.cache/volatility3.tar.gz'
    with archive.open('rb') as stream:
        if hashlib.file_digest(stream, 'sha256').hexdigest() != lock['archive_sha256']:
            raise ValueError('baseline archive checksum mismatch')
    with tarfile.open(archive) as tar:
        for path in (source / 'volatility3/framework/symbols/windows/services').glob('*.json'):
            member = f'volatility3-{COMMIT}/' + path.relative_to(source).as_posix()
            if tar.extractfile(member).read() != path.read_bytes():
                raise ValueError(f'modified service ISF: {path}')
    sys.path.insert(0, str(source))
    from volatility3.framework import contexts, interfaces, renderers
    from volatility3.framework.layers.physical import BufferDataLayer
    from volatility3.framework.symbols import intermed
    from volatility3.framework.symbols.windows.extensions import services
    from volatility3.plugins.windows.svcscan import SvcScan, ServiceBinaryInfo
    class ProcessBuffer(BufferDataLayer):
        @property
        def address_mask(self):
            return (1 << (32 if self.name.endswith('32') else 48)) - 1
    files = sorted((source / 'volatility3/framework/symbols/windows/services').glob('*.json'))
    facts = ['// Code generated by tools/build_service_oracle.py; DO NOT EDIT.', 'package plugins', 'var serviceLayouts = map[string]serviceLayout{']
    cases = []
    for path in files:
        data = json.loads(path.read_text())
        types = data['user_types']
        rec = types['_SERVICE_RECORD']['fields']
        proc = types['_SERVICE_PROCESS']['fields']
        width = data['base_types']['pointer']['size']
        offsets = [types['_SERVICE_HEADER']['fields']['ServiceRecord']['offset'], rec.get('PrevEntry', {'offset': 0})['offset']]
        offsets += [rec[n]['offset'] for n in ['Order', 'Start', 'ServiceName', 'DisplayName', 'Type', 'State', 'ServiceProcess', 'DriverName']]
        offsets += [proc[n]['offset'] for n in ['BinaryPath', 'ProcessId']]
        offsets += [rec['Tag']['offset']]
        legacy = 'PrevEntry' not in rec
        facts.append(f'"{path.stem}": {{"{path.stem}", {width}, '+', '.join(map(str, offsets))+f', {str(legacy).lower()}'+'},')
        for scenario in ['process', 'driver', 'stopped', 'invalid-order', 'invalid-start', 'invalid-state', 'unreadable-name', 'unreadable-pid', 'unreadable-binary', 'masked-pointer', 'null-name', 'null-process', 'truncated-record', 'truncated-text']:
            buf = bytearray(0x3000)
            base, header, process = 0x400, 0x100, 0x800
            def u32(addr, value):
                struct.pack_into('<I', buf, addr, value)
            def ptr(addr, value):
                struct.pack_into('<I' if width == 4 else '<Q', buf, addr, value)
            def string(addr, text):
                raw = text.encode('utf-16le') + b'\0\0'
                buf[addr:addr+len(raw)] = raw
            def field(name, value, pointer=False):
                (ptr if pointer else u32)(base + rec[name]['offset'], value)
            ptr(header + offsets[0], base)
            field('Order', 17 if scenario != 'invalid-order' else 65536)
            field('Start', 2 if scenario != 'invalid-start' else 9)
            field('State', 1 if scenario == 'stopped' else 99 if scenario == 'invalid-state' else 4)
            field('Type', 1 if scenario == 'driver' else 32 | 256)
            field('ServiceName', 0x5000 if scenario == 'unreadable-name' else 0x1000, True)
            field('DisplayName', 0x1400, True)
            field('ServiceProcess', 0x5000 if scenario == 'unreadable-pid' else process, True)
            if scenario == 'driver':
                field('DriverName', 0x1800, True)
            ptr(process + proc['BinaryPath']['offset'], 0x5000 if scenario == 'unreadable-binary' else 0x1800)
            u32(process + proc['ProcessId']['offset'], 1234)
            if scenario == 'null-name':
                field('ServiceName', 0, True)
            if scenario == 'null-process':
                field('ServiceProcess', 0, True)
            if scenario == 'masked-pointer' and width == 8:
                field('ServiceName', 0xabcd000000001000, True)
                field('ServiceProcess', 0xabcd000000000800, True)
            string(0x1000, 'example')
            string(0x1400, 'Example service')
            string(0x1800, r'\Driver\example' if scenario == 'driver' else r'C:\Windows\example.exe')
            if scenario == 'truncated-record':
                buf = buf[:base + rec['Order']['offset'] + 3]
            elif scenario == 'truncated-text':
                buf = buf[:0x18f0]
            ctx = contexts.Context()
            layer = ProcessBuffer(ctx, 'fixture', 'memory32' if width == 4 else 'memory64', bytes(buf))
            ctx.layers.add_layer(layer)
            table = intermed.IntermediateSymbolTable(ctx, 'fixture.symbols', 'services', path.as_uri(), class_types=services.class_types)
            ctx.symbol_space.append(table)
            record = ctx.object('services!_SERVICE_RECORD', layer_name=layer.name, offset=base)
            valid = record.is_valid()
            expected = None
            if valid:
                info = ServiceBinaryInfo('example.dll', 'registry.exe') if record.get_name() == 'example' else ServiceBinaryInfo(renderers.UnreadableValue(), renderers.UnreadableValue())
                raw = SvcScan.get_record_tuple(record, info)
                expected = [None if isinstance(v, interfaces.renderers.BaseAbsentValue) else int(v) if isinstance(v, int) else str(v) for v in raw]
            cases.append(dict(layout=path.stem, scenario=scenario, address=base, size=len(buf), segments=[dict(offset=off, hex=bytes(buf[off:off+256]).rstrip(b'\0').hex()) for off in range(0, len(buf), 256) if any(buf[off:off+256])], valid=valid, expected=expected))
    facts.append('}')
    go = subprocess.run(['gofmt'], input='\n'.join(facts)+'\n', text=True, check=True, capture_output=True).stdout
    fixture = dict(schema='gomem.service-oracle/v1', commit=COMMIT, layouts=len(files), producer='pinned ISFs and SERVICE_RECORD/SvcScan.get_record_tuple', cases=cases)
    return go, json.dumps(fixture, indent=2)+'\n'


def version_oracle():
    from volatility3.framework import exceptions
    from volatility3.framework.symbols.windows import versions
    from volatility3.plugins.windows.svcscan import SvcScan
    class Space:
        def __init__(self, pe, types, symbols):
            self.pe, self.types, self.symbols = pe, types, symbols
        def __getitem__(self, name):
            return SimpleNamespace(metadata=SimpleNamespace(pe_version=self.pe))
        def has_symbol(self, name):
            return name.split('!')[-1] in self.symbols
        def has_type(self, name):
            return name.split('!')[-1] in self.types
        def get_type(self, name):
            name = name.split('!')[-1]
            if name not in self.types:
                raise exceptions.SymbolError(name, 'kernel')
            return SimpleNamespace(has_member=lambda member: member in self.types[name])
    inputs = []
    for width in [4, 8]:
        for major, minor, revision in [(5,0,0),(5,1,2600),(5,2,3790),(6,0,6000),(6,1,7601),(6,2,9200),(6,3,9600)] + [(10,0,n) for n in [10240,15062,15063,15064,16298,16299,17763,18362,19040,19041,25397,25398]]:
            for build in [None, 0, 123]:
                pe = dict(major=major,minor=minor,revision=revision)
                if build is not None:
                    pe['build'] = build
                inputs.append(dict(width=width, pe=pe, types={}, symbols=[]))
        common = {'_EPROCESS': [], '_HANDLE_TABLE': []}
        fallback_sets = [
            ({}, []),
            ({'_HANDLE_TABLE':['HandleCount']}, []),
            (common, ['KdCopyDataBlock']),
            (dict(common, _EPROCESS=['KeepAliveCounter']), ['ObHeaderCookie','KdCopyDataBlock']),
            (dict(common, _EPROCESS=['ControlFlowGuardEnabled']), ['ObHeaderCookie','KdCopyDataBlock']),
            (common, ['ObHeaderCookie','KdCopyDataBlock']),
            (common, ['ParentSecurityDomain','KdCopyDataBlock']),
            (dict(common, _WNF_PROCESS_CONTEXT=[]), ['ObHeaderCookie','KdCopyDataBlock']),
            (dict(common, _KQOS_GROUPING_SETS=[], _EPROCESS=['TimerResolutionIgnore','VmProcessorHostTransition']), ['KdCopyDataBlock']),
            (dict(common, _EPROCESS=['MmSlabIdentity','EnableProcessImpersonationLogging']), ['KdCopyDataBlock']),
            ({'_HANDLE_TABLE':[]}, ['ObHeaderCookie']),
        ]
        for types, symbols in fallback_sets:
            inputs.append(dict(width=width, pe=None, types=types, symbols=symbols))
    for item in inputs:
        pe = item['pe']
        value = None if pe is None else tuple(pe[n] for n in ['major','minor','revision','build'] if n in pe)
        context = SimpleNamespace(symbol_space=Space(value,item['types'],item['symbols']))
        item['layout'] = next((name for predicate, x64, name in SvcScan._win_version_file_map if (item['width'] == 8) == x64 and predicate(context,'kernel')), '')
        item['list_supported'] = item['width'] == 8 and versions.is_win10_15063_or_later(context,'kernel')
        item['vista'] = versions.is_vista_or_later(context,'kernel')
    return json.dumps(dict(commit=COMMIT, cases=inputs), indent=2) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=ROOT / '.cache' / ('volatility3-' + COMMIT))
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    go, fixture = generate(args.source.resolve())
    for path, content in [(FACTS, go), (OUTPUT, fixture), (VERSIONS, version_oracle())]:
        if args.check:
            if path.read_text() != content:
                raise ValueError(f'{path} differs from pinned service oracle')
        else:
            path.write_text(content)
    print('16 service layouts, 224 service objects and 136 version selections verified')


if __name__ == '__main__':
    main()
